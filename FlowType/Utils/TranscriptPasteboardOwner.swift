import AppKit
import Foundation

/// Owns a transcript put on the pasteboard as a promise. The text is handed
/// out only when another app asks for it, so each request is evidence that
/// the paste target has actually read the transcript.
final class TranscriptPasteboardOwner: NSObject {
    /// Markers that clipboard managers (Maccy, Paste, Raycast) honour by not
    /// recording the item: the transcript is a transient paste, not a copy
    /// the user made.
    static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    private let text: String
    private(set) var lastTextReadAt: ContinuousClock.Instant?
    private(set) var hasLostOwnership = false

    init(text: String) {
        self.text = text
    }
}

extension TranscriptPasteboardOwner: NSPasteboardTypeOwner {
    func pasteboard(_ sender: NSPasteboard, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .string else {
            // The markers carry no data. A request for one is a clipboard
            // manager checking them, not the paste target.
            sender.setData(Data(), forType: type)
            return
        }

        lastTextReadAt = .now
        sender.setString(text, forType: .string)
    }

    func pasteboardChangedOwner(_ sender: NSPasteboard) {
        hasLostOwnership = true
    }
}
